"""Controlled CPU latency benchmark of re-ranker backends on real candidates.

Same queries, same passages (first-stage top-n of exported candidates), same thread count, warm-up
excluded, one backend at a time. Writes reports/rerank-latency.md and runs/bench-rerank/results.json.

Usage:
  python scripts/bench_reranker.py --torch models/C2-listwise-scifact \
      --onnx models/C2-listwise-scifact-onnx --onnx-int8 models/C2-listwise-scifact-onnx-int8
"""
from __future__ import annotations

import argparse
import json
import platform
import time
from pathlib import Path

import numpy as np

from cer.config import RerankConfig
from cer.rerank import build_reranker, passage_text
from cer.rerank.candidates import read_candidates

SETTINGS = [(20, 20), (50, 16), (50, 32), (50, 50)]  # (passages per query, batch size)


def cpu_name() -> str:
    try:
        if platform.system() == "Windows":
            import winreg
            key = r"HARDWARE\DESCRIPTION\System\CentralProcessor\0"
            with winreg.OpenKey(winreg.HKEY_LOCAL_MACHINE, key) as k:
                return str(winreg.QueryValueEx(k, "ProcessorNameString")[0]).strip()
        for line in Path("/proc/cpuinfo").read_text().splitlines():
            if line.startswith("model name"):
                return line.split(":", 1)[1].strip()
    except OSError:
        pass
    return platform.processor() or "unknown CPU"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--candidates", default="runs/nfcorpus-hybrid/candidates-dev.jsonl")
    ap.add_argument("--queries", type=int, default=30)
    ap.add_argument("--warmup", type=int, default=3)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--max-length", type=int, default=256)
    ap.add_argument("--torch", dest="torch_model", default=None)
    ap.add_argument("--onnx", default=None)
    ap.add_argument("--onnx-int8", default=None)
    ap.add_argument("--out", default="reports/rerank-latency.md")
    args = ap.parse_args()

    import torch
    torch.set_num_threads(args.threads)
    records = list(read_candidates(args.candidates))[: args.queries + args.warmup]
    backends = [(name, typ, path) for name, typ, path in [("PyTorch fp32", "cross-encoder", args.torch_model),
                                                          ("ONNX Runtime fp32", "onnx", args.onnx),
                                                          ("ONNX Runtime int8 (dynamic)", "onnx", args.onnx_int8)]
                if path]
    results = []
    for name, typ, path in backends:
        for n, bs in SETTINGS:
            rr = build_reranker(RerankConfig(type=typ, model=path, max_length=args.max_length, batch_size=bs,
                                             threads=args.threads, device="cpu"))
            times = []
            for i, r in enumerate(records):
                ps = [passage_text(c["title"], c["text"]) for c in r["candidates"][:n]]
                t0 = time.perf_counter()
                rr.score(r["query"], ps)
                if i >= args.warmup:
                    times.append((time.perf_counter() - t0) * 1e3)
            a = np.asarray(times)
            results.append({"backend": name, "model": path, "passages": n, "batch_size": bs, "queries": len(a),
                            "p50_ms": float(np.percentile(a, 50)), "p95_ms": float(np.percentile(a, 95)),
                            "mean_ms": float(a.mean()), "pairs_per_s": float(n * len(a) / (a.sum() / 1e3))})
            print(json.dumps(results[-1]), flush=True)

    hw = f"{cpu_name()}, {args.threads} threads, no GPU"
    import onnxruntime
    import transformers
    versions = f"torch {torch.__version__}, onnxruntime {onnxruntime.__version__}, transformers {transformers.__version__}"
    out_json = Path("runs/bench-rerank/results.json")
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps({"hardware": hw, "versions": versions, "args": vars(args), "results": results},
                                   indent=2), encoding="utf-8")
    lines = ["# Re-ranker latency (CPU)", "",
             f"Generated by `scripts/bench_reranker.py`. Hardware: {hw}. {versions}.",
             (f"Candidates: `{args.candidates}`, {args.queries} queries after {args.warmup} warm-up queries, "
              f"max length {args.max_length} tokens, passages ≈ 220 words (truncated). Time per query = scoring "
              "all its passages (tokenization included)."), "",
             "| backend | passages | batch | p50 ms | p95 ms | pairs/s |", "|---|---|---|---|---|---|"]
    lines += [f"| {r['backend']} | {r['passages']} | {r['batch_size']} | {r['p50_ms']:.0f} | {r['p95_ms']:.0f} | "
              f"{r['pairs_per_s']:.1f} |" for r in results]
    Path(args.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
